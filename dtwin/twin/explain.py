"""
Calculation traces behind the four Overview tiles (hot-spot, load, top oil,
health index).

Each trace is built by CALLING the same functions that produce the tile, at
the same cursor sample, so the final value of a trace is the tile value and
check_explain.py asserts that. Nothing here feeds back into the engine: it is
read-only and no existing output depends on it.

A trace carries: meaning, equations with variable tables and provenance, the
substituted steps, a model sweep for the graph (one input varied, the rest
held, clearly a model curve and not history), a sensitivity table, and data
quality. Missing inputs are named, never filled in.

Provenance vocabulary (same style as the calibration badges, plus two):
NAMEPLATE, DERIVED, ASSUMED, MEASURED, SIMULATED. A channel in a record that
was generated by the simulator is labelled SIMULATED, never MEASURED.
"""

import math

import numpy as np

from ..api import engine as E
from ..physics import unbalance as ub
from ..physics.ageing import ageing_factor
from ..physics.thermal import hotspot_rise_ultimate, top_oil_rise_ultimate

METRICS = ("hotspot", "load", "top_oil", "health")
SWEEP_K = [round(0.05 * k, 2) for k in range(0, 31)]          # 0 .. 1.5 pu


# ----------------------------------------------------------------- helpers
def _num(x):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return None
    return x if math.isfinite(x) else None


def _r(x, nd=2):
    x = _num(x)
    return None if x is None else round(x, nd)


def _origin(tw):
    """Where the numbers in this record come from. Truth files are only
    checked for existence, never read."""
    if tw.name == "live":
        return {"synthetic": True, "label": "SIMULATED",
                "text": "Live stream. Its source is the step simulator unless a hardware feed is attached; "
                        "treated as simulated here so it is never presented as a sensor reading."}
    if (E.DATA / f"{tw.name}_truth.csv").exists():
        return {"synthetic": True, "label": "SIMULATED",
                "text": f"{tw.name}.csv was produced by the project's SCADA-style generator (dtwin/simulate). "
                        "Its \"measured\" channels are generated values, not readings from a real transformer."}
    return {"synthetic": False, "label": "MEASURED",
            "text": "Channels come from the supplied record. Their accuracy is that of the field instruments."}


class _Src:
    def __init__(self, origin):
        self.measured = origin["label"]

    def __call__(self, kind):
        return self.measured if kind == "MEASURED" else kind


def _var(sym, meaning, unit, source, value=None, note=None):
    return {"sym": sym, "meaning": meaning, "unit": unit, "source": source, "value": _r(value, 4),
            "note": note}


def _step(label, expr, sub, value, unit, source, nd=2):
    return {"label": label, "expr": expr, "substituted": sub, "value": _r(value, nd), "unit": unit,
            "source": source}


def _graph(title, xlabel, ylabel, x, ys, point, note, vlines=None, hlines=None):
    return {"kind": "model sweep", "title": title, "xlabel": xlabel, "ylabel": ylabel, "x": x,
            "series": [{"name": n, "y": [_r(v, 2) for v in y]} for n, y in ys],
            "point": point, "note": note, "vlines": vlines or [], "hlines": hlines or []}


def _sens(name, unit, cur, new, before, after, out_unit, rise=False, note=""):
    d = None if before is None or after is None else after - before
    pct = None
    if d is not None and rise and before and abs(before) > 1e-9:
        pct = 100.0 * d / before        # a ratio is only meaningful for a quantity with a physical zero
    return {"input": name, "unit": unit, "current": _r(cur, 3), "perturbed": _r(new, 3),
            "before": _r(before, 2), "after": _r(after, 2), "delta": _r(d, 2), "pct": _r(pct, 1),
            "out_unit": out_unit, "note": note}


def _context(tw, i):
    r, np_ = tw.rows, tw.np_
    row = r.iloc[i]
    ko, kw = _num(row.K_oil), _num(row.K_winding)
    ratio_w = (kw / ko) if ko and kw is not None and ko > 0 else 1.0
    cf = float(row.slope) if row.thermal_status == "asset_cooling" and _num(row.slope) else 1.0
    return {"r": r, "row": row, "np": np_, "ko": ko, "kw": kw, "ratio_w": ratio_w, "cf": cf,
            "amb": _num(row.ambient_c), "t": r.index[i]}


def _quality(tw, c, origin, extra=()):
    row = c["row"]
    notes = [origin["text"],
             "Model parameters (rises, exponents, time constants) are the preset for the declared kVA rating, "
             "not this unit's test data, unless a test report has been applied (Engineering > Calibration)."]
    sus = [s for s in str(row.suspect_channels or "").split(",") if s]
    if sus:
        notes.append("Channels currently suspect: " + ", ".join(sus) + ". Values derived from them are not trusted.")
    notes.extend(extra)
    return {"origin": origin["label"], "synthetic": origin["synthetic"], "notes": notes,
            "model": "IEEE C57.91 clause 7 exponential model (same as IEC 60076-7 structure), first-order lags"}


def _base(tw, i, metric):
    c = _context(tw, i)
    o = _origin(tw)
    return c, o, _Src(o), {"metric": metric, "scenario": tw.name, "i": int(i),
                           "timestamp": c["t"].isoformat(), "missing": []}


# ------------------------------------------------------------------- load
def _load(tw, i):
    c, o, S, out = _base(tw, i, "load")
    row, np_, df = c["row"], c["np"], tw.df.iloc[i]
    cur = {p: _num(df[f"I{p}"]) for p in ("R", "Y", "B")}
    miss = [f"I{p}" for p, v in cur.items() if v is None]
    out["missing"] = miss
    final = E._f(100 * row.K_oil, 0)
    out["final"] = {"value": final, "unit": "% of rating", "tile": "readings.load_pct"}
    out["meaning"] = {
        "definition": "Load ratio K: the RMS of the three phase currents, corrected for the extra heating of "
                      "unbalance, divided by the rated current. It is the input that drives copper loss and so the oil.",
        "unit": "% of rated current (per unit when divided by 100)",
        "normal": "Below 90 % is normal; 100 % is rated load, where the overload alarm fires.",
        "why": "Copper loss grows with the square of current, so heating, and with it insulation wear, rise fast above rating."}
    ratedA = np_.rated_current_a
    out["equations"] = [{
        "id": "K", "tex": "K = I_rms × √(1 + 2(u/100)²) / I_rated,   I_rms = √((I_R² + I_Y² + I_B²) / 3)",
        "vars": [_var("I_R, I_Y, I_B", "phase currents", "A", S("MEASURED")),
                 _var("u", "NEMA current unbalance", "%", "DERIVED", _num(row.current_unbalance_pct)),
                 _var("I_rated", "rated phase current from kVA and LV voltage", "A", "NAMEPLATE", ratedA)],
        "assumptions": ["The derating factor 1 + 2(u/100)² on loss is the conservative NEMA-style approximation, "
                        "applied as a small correction."],
        "valid": "Three phase currents available and trusted. A failed channel is repaired from the other two "
                 "before this is evaluated (dtwin/analytics/validation.py)."}]
    steps = []
    if not miss:
        i_rms, i_max, unb = ub.equivalent_currents(cur["R"], cur["Y"], cur["B"])
        i_rms, unb = float(np.ravel(i_rms)[0]), float(np.ravel(unb)[0])
        der = float(np.ravel(ub.unbalance_derating_factor(unb))[0])
        steps = [
            _step("Phase currents", "I_R, I_Y, I_B", f"{cur['R']:.1f}, {cur['Y']:.1f}, {cur['B']:.1f} A",
                  None, "A", S("MEASURED")),
            _step("RMS of the three phases", "√((I_R²+I_Y²+I_B²)/3)",
                  f"√(({cur['R']:.1f}² + {cur['Y']:.1f}² + {cur['B']:.1f}²)/3)", i_rms, "A", "DERIVED"),
            _step("NEMA unbalance", "max|I − I_avg| / I_avg × 100", "from the three currents", unb, "%", "DERIVED"),
            _step("Unbalance derating", "√(1 + 2(u/100)²)", f"√(1 + 2·({unb:.2f}/100)²)", der, "", "DERIVED", 4),
            _step("Rated current", "S / (√3 × V_LL)", f"{np_.rating_kva:g} kVA at {np_.lv_v:g} V", ratedA, "A", "NAMEPLATE", 1),
            _step("Load ratio K", "I_rms × derating / I_rated", f"{i_rms:.1f} × {der:.4f} / {ratedA:.1f}",
                  i_rms * der / ratedA, "pu", "DERIVED", 4)]
        if bool(row.currents_repaired):
            out["missing"].append("one or more currents were repaired from the other phases before use; "
                                  "the tile uses the repaired values, so the recomputation above can differ")
    out["steps"] = steps
    out["steps"].append(_step("Displayed load", "100 × K", f"100 × {_r(row.K_oil, 4)}", final, "%", "DERIVED", 0))

    # sweep: copper loss ~ K^2, hot-spot rise follows; graph copper-loss ratio and oil rise vs K
    xs = SWEEP_K
    ko = c["ko"]
    out["graph"] = _graph(
        "Heat produced against load (model)", "Load ratio K (pu)", "Relative copper loss K² (pu of rated)", xs,
        [("Copper loss, K²", [k * k for k in xs])],
        {"x": _r(ko, 3), "y": _r(ko * ko if ko is not None else None, 3), "label": "operating point"},
        "Model curve with the resistance held constant. The point is the present load; the line is not history.",
        vlines=[{"x": 1.0, "label": "rated"}])
    sens = []
    if ko is not None:
        sens.append(_sens("Load K +10 %", "pu", ko, ko * 1.1, ko * ko, (ko * 1.1) ** 2, "pu of rated copper loss",
                          rise=True, note="P = I²R: a 10 % increase in current is a 21 % increase in loss, resistance held constant."))
    out["sensitivity"] = sens
    out["quality"] = _quality(tw, c, o)
    return out


# ------------------------------------------------------------------ top oil
def _top_oil(tw, i):
    c, o, S, out = _base(tw, i, "top_oil")
    row, np_, ko, amb = c["row"], c["np"], c["ko"], c["amb"]
    final = E._f(row.oil_c, 1)
    out["final"] = {"value": final, "unit": "°C", "tile": "readings.oil_c"}
    out["meaning"] = {
        "definition": "Oil temperature at the top of the tank, read by the oil probe. The twin predicts the same "
                      "quantity from load and ambient; the difference is the thermal residual.",
        "unit": "°C", "normal": "Below 95 °C; 105 °C is the IEC 60076-7 top-oil limit for normal cyclic loading.",
        "why": "The oil carries the heat from the windings to the radiators. A reading above what load and ambient "
               "explain is the first sign of a cooling problem or of a faulty probe."}
    out["equations"] = [{
        "id": "oil", "tex": "Δθ_TO,ult = Δθ_TO,R × ((K²·R + 1) / (R + 1))ⁿ,    θ_TO = θ_A + Δθ_TO",
        "vars": [_var("Δθ_TO,R", "top-oil rise over ambient at rated load", "K", "NAMEPLATE", np_.top_oil_rise_rated_k),
                 _var("K", "load ratio", "pu", "DERIVED", ko),
                 _var("R", "load loss / no-load loss at rating", "", "NAMEPLATE", np_.loss_ratio_R),
                 _var("n", "oil exponent (0.8 ONAN)", "", "NAMEPLATE", np_.n_exponent),
                 _var("θ_A", "ambient temperature", "°C", S("MEASURED"), amb)],
        "assumptions": ["The model rise is approached as a first-order lag with τ = "
                        f"{np_.tau_oil_h:g} h, so the instantaneous prediction trails the steady state.",
                        "Parameters are the preset for the declared rating (self-consistent by design)."],
        "valid": "Natural oil cooling (ONAN), ambient measured by a trusted probe."}]
    steps = [_step("Measured top oil (this tile)", "θ_TO", "oil probe reading", row.oil_c, "°C", S("MEASURED"), 1)]
    if amb is None or ko is None:
        out["missing"] = [n for n, v in (("ambient_temp", amb), ("load K", ko)) if v is None]
    else:
        ult = float(top_oil_rise_ultimate(ko, np_))
        ratio = (ko ** 2 * np_.loss_ratio_R + 1) / (np_.loss_ratio_R + 1)
        steps = [
            _step("Loss-ratio term", "(K²R + 1)/(R + 1)", f"({ko:.3f}²·{np_.loss_ratio_R:g} + 1)/({np_.loss_ratio_R:g} + 1)",
                  ratio, "", "DERIVED", 4),
            _step("Steady top-oil rise", "Δθ_TO,R × term^n",
                  f"{np_.top_oil_rise_rated_k:g} × {ratio:.4f}^{np_.n_exponent:g}", ult, "K", "DERIVED"),
            _step("Steady top oil", "θ_A + Δθ", f"{amb:.1f} + {ult:.2f}", amb + ult, "°C", "DERIVED", 1),
            _step("Predicted now (lagged)", "C57.91 first-order lag", f"{np_.tau_oil_h:g} h time constant",
                  row.pred_oil_c, "°C", "DERIVED", 1),
            _step("Measured top oil (this tile)", "θ_TO", "oil probe reading", row.oil_c, "°C", S("MEASURED"), 1),
            _step("Residual", "measured − predicted", f"{row.oil_c:.1f} − {row.pred_oil_c:.1f}",
                  row.oil_c - row.pred_oil_c, "K", "DERIVED")]
    out["steps"] = steps

    xs = SWEEP_K
    if amb is not None:
        steady = [amb + c["cf"] * float(top_oil_rise_ultimate(k, np_)) for k in xs]
        out["graph"] = _graph(
            "Steady-state top oil against load (model)", "Load ratio K (pu)", "Top-oil temperature (°C)", xs,
            [("Steady-state top oil", steady)],
            {"x": _r(ko, 3), "y": _r(row.oil_c, 1), "label": "measured now"},
            f"Ambient held at {amb:.1f} °C, cooling factor {c['cf']:.2f}. The point is the measured oil now; it sits "
            "off the line while the oil is still approaching steady state (τ ≈ hours) or when cooling has changed.",
            hlines=[{"y": 105, "label": "105 °C IEC limit"}])
        sens = []
        if ko is not None:
            b, a = amb + c["cf"] * float(top_oil_rise_ultimate(ko, np_)), amb + c["cf"] * float(top_oil_rise_ultimate(ko * 1.1, np_))
            sens.append(_sens("Load K +10 %", "pu", ko, ko * 1.1, b, a, "°C steady top oil",
                              note="Steady-state model value; percentage not given because °C has no physical zero."))
            sens.append(_sens("Ambient +5 K", "°C", amb, amb + 5, b, b + 5, "°C steady top oil",
                              note="Every absolute temperature shifts by the same amount; the rises are unchanged."))
        out["sensitivity"] = sens
    else:
        out["graph"], out["sensitivity"] = None, []
    out["quality"] = _quality(tw, c, o, extra=[
        "This tile is the probe reading; the equation produces the prediction it is compared with."])
    return out


# ------------------------------------------------------------------ hot-spot
def _hotspot(tw, i):
    c, o, S, out = _base(tw, i, "hotspot")
    row, np_, ko, kw, amb = c["row"], c["np"], c["ko"], c["kw"], c["amb"]
    final = E._f(row.hotspot_c, 1)
    out["final"] = {"value": final, "unit": "°C", "tile": "readings.hotspot_c"}
    out["meaning"] = {
        "definition": "Temperature of the hottest point in the windings: top oil plus the winding gradient of "
                      "the most loaded phase.",
        "unit": "°C", "normal": f"Below {np_.reference_hotspot_c:g} °C insulation wears at its rated speed; "
                                "amber from 110 °C, red from 120 °C.",
        "why": "It sets the insulation ageing rate, which roughly doubles every 6 to 7 K above the reference."}
    oil_ok = str(row.ch_oil_temp) in ("ok", "step") and row.thermal_status != "sensor_temp_offset"
    grad = float(row.pred_hotspot_c - row.pred_oil_c)
    out["equations"] = [
        {"id": "hs", "tex": "θ_HS = θ_TO + Δθ_HS,   Δθ_HS,ult = Δθ_HS,R × K_w^(2m)",
         "vars": [_var("θ_TO", "top-oil temperature (measured if the probe is trusted, else predicted)", "°C",
                       S("MEASURED") if oil_ok else "DERIVED", row.oil_c if oil_ok else row.pred_oil_c),
                  _var("Δθ_HS", "winding gradient: hot-spot over top oil, lagged", "K", "DERIVED", grad),
                  _var("Δθ_HS,R", "gradient at rated current", "K", "NAMEPLATE", np_.hotspot_rise_rated_k),
                  _var("K_w", "load ratio of the worst phase", "pu", "DERIVED", kw),
                  _var("m", "winding exponent", "", "NAMEPLATE", np_.m_exponent)],
         "assumptions": [f"The gradient is approached with a {np_.tau_winding_min:g} min lag, so it trails K_w^(2m).",
                         "Hot-spot is NOT predicted ambient + oil rise + gradient here when the probe is trusted: "
                         "measured oil already carries any extra rise from a cooling fault."],
         "valid": "Oil probe trusted for the measured path; otherwise the fully predicted hot-spot is shown."}]
    steps = []
    if kw is None:
        out["missing"] = ["K_w (phase currents)"]
    else:
        ult = float(hotspot_rise_ultimate(kw, np_))
        steps = [
            _step("Worst-phase load", "K_w", f"max phase current × derating / {np_.rated_current_a:.1f} A", kw, "pu", "DERIVED", 3),
            _step("Steady winding gradient", "Δθ_HS,R × K_w^(2m)",
                  f"{np_.hotspot_rise_rated_k:g} × {kw:.3f}^{2 * np_.m_exponent:g}", ult, "K", "DERIVED"),
            _step("Gradient now (lagged)", "θ_HS,pred − θ_TO,pred", f"{row.pred_hotspot_c:.1f} − {row.pred_oil_c:.1f}",
                  grad, "K", "DERIVED"),
            _step("Top oil used", "measured if trusted else predicted", "oil probe" if oil_ok else "predicted",
                  row.oil_c if oil_ok else row.pred_oil_c, "°C", S("MEASURED") if oil_ok else "DERIVED", 1),
            _step("Hot-spot", "θ_TO + Δθ_HS", f"{(row.oil_c if oil_ok else row.pred_oil_c):.1f} + {grad:.2f}",
                  row.hotspot_c, "°C", "DERIVED", 1)]
    out["steps"] = steps
    if amb is not None and ko is not None:
        xs = SWEEP_K
        y = [E.steady_hotspot_cf(k, c["ratio_w"], amb, c["cf"], np_) for k in xs]
        out["graph"] = _graph(
            "Steady-state hot-spot against load (model)", "Load ratio K (pu)", "Hot-spot temperature (°C)", xs,
            [("Steady-state hot-spot", y)],
            {"x": _r(ko, 3), "y": _r(row.hotspot_c, 1), "label": "hot-spot now"},
            f"Ambient held at {amb:.1f} °C, cooling factor {c['cf']:.2f}, phase ratio {c['ratio_w']:.3f}. "
            "The curve is where the hot-spot settles for each load; the point is the value now and can sit off "
            "the curve while the unit is still warming or cooling.",
            hlines=[{"y": 110, "label": "110 °C ageing reference"}, {"y": 120, "label": "120 °C alarm"}])
        f = lambda k, a: E.steady_hotspot_cf(k, c["ratio_w"], a, c["cf"], np_)
        b = f(ko, amb)
        out["sensitivity"] = [
            _sens("Load K +10 %", "pu", ko, ko * 1.1, b, f(ko * 1.1, amb), "°C steady hot-spot",
                  note="Steady-state model value. Rises scale with K^(2m); °C has no physical zero, so no percentage."),
            _sens("Ambient +5 K", "°C", amb, amb + 5, b, f(ko, amb + 5), "°C steady hot-spot",
                  note="Same shift in every temperature; the rises are unchanged."),
            _sens("Cooling factor +10 %", "x", c["cf"], c["cf"] * 1.1, b,
                  E.steady_hotspot_cf(ko, c["ratio_w"], amb, c["cf"] * 1.1, np_), "°C steady hot-spot",
                  note="A degraded cooling path scales the oil rise (higher effective thermal resistance).")]
        fa_b, fa_a = float(ageing_factor(b, np_)), float(ageing_factor(f(ko * 1.1, amb), np_))
        out["sensitivity"].append(_sens("Ageing factor, load +10 %", "pu", ko, ko * 1.1, fa_b, fa_a, "pu F_AA",
                                        rise=True, note="C57.91 ageing law: exp(15000/383 − 15000/(θ_HS+273))."))
    else:
        out["graph"], out["sensitivity"] = None, []
        out["missing"] += [n for n, v in (("ambient_temp", amb), ("load K", ko)) if v is None]
    out["quality"] = _quality(tw, c, o)
    return out


# -------------------------------------------------------------------- health
def _health_from(comps, hs_override=None):
    """The index from a component list, by the same rule as Twin.health."""
    tot = wsum = 0.0
    scores = {}
    for k in comps:
        if k["score"] is None:
            continue
        tot += k["weight"] * k["score"]
        wsum += k["weight"]
        scores[k["key"]] = k["score"]
    mean = tot / wsum if wsum else None
    crit = [scores[k] for k in E.SAFETY_CRITICAL if k in scores]
    cap = min(crit) + E.CAP_MARGIN if crit else None
    if mean is None:
        return None
    return min(mean, cap) if cap is not None and cap < mean else mean


def _health(tw, i):
    c, o, S, out = _base(tw, i, "health")
    h = tw.health(i)
    np_ = c["np"]
    out["final"] = {"value": h["index"], "unit": "of 100", "tile": "health.index"}
    out["meaning"] = {
        "definition": "A 0 to 100 summary of five physical scores. 100 is healthy behaviour; each score reaches 0 "
                      "where its own alarm fires. Higher is better.",
        "unit": "points (100 best)",
        "normal": "80 or more is normal; 40 to 80 amber; below 40 red.",
        "why": "It is a summary only. Each component below is a physical quantity that is displayed and "
               "explained on its own."}
    out["equations"] = [{
        "id": "HI", "tex": "HI = min( Σ wᵢ·Sᵢ / Σ wᵢ ,  min(S_ageing, S_loading) + 10 )",
        "vars": [_var("Sᵢ", "component score 0 to 100", "", "DERIVED"),
                 _var("wᵢ", "weight (a stated judgement)", "", "ASSUMED"),
                 _var("+10", "cap margin: an extreme hot-spot must drive the index near 0", "points", "ASSUMED")],
        "assumptions": ["Weights: ageing 0.30, cooling 0.25, loading 0.20, integrity 0.15, unbalance 0.10.",
                        "A component with no data is dropped and the remaining weights are renormalised.",
                        "Ageing is scored on log₂(F_AA); the others linearly between their 100 and 0 values."],
        "valid": "Always defined while at least one component can be scored."}]
    steps = []
    for k in h["components"]:
        if k["score"] is None:
            steps.append({**_step(k["label"], "weight × score", "not scored: no data", None, "pts", "DERIVED", 1),
                          "weight": k["weight"], "score": None, "contribution": None, "scale": k.get("scale", "")})
            continue
        contrib = k["weight"] * k["score"]
        steps.append({**_step(k["label"], "wᵢ × Sᵢ", f"{k['weight']:.2f} × {k['score']:g}", contrib, "pts", "DERIVED", 1),
                      "weight": k["weight"], "score": k["score"], "contribution": _r(contrib, 2),
                      "input_value": k["value"], "input_unit": k["unit"], "scale": k.get("scale", "")})
    steps.append(_step("Weighted mean", "Σ wᵢSᵢ / Σ wᵢ", "over the scored components", h["weighted_mean"], "pts", "DERIVED", 0))
    if h["capped_by"]:
        steps.append(_step("Cap", "min(S_ageing, S_loading) + 10", h["cap_rule"], None, "pts", "DERIVED", 0))
    steps.append(_step("Health index", "min(mean, cap)", f"capped by {h['capped_by']}" if h["capped_by"] else "cap not active",
                       h["index"], "pts", "DERIVED", 0))
    out["steps"] = steps
    out["components"] = h["components"]
    out["cap"] = {"rule": h["cap_rule"], "active": h["capped_by"]}

    # sweep: index against steady-state load, the other three components held at their present scores
    ko, amb = c["ko"], c["amb"]
    if ko is not None and amb is not None:
        held = [k for k in h["components"] if k["key"] not in ("ageing", "loading")]
        ageing_c = next(k for k in h["components"] if k["key"] == "ageing")
        loading_c = next(k for k in h["components"] if k["key"] == "loading")
        good, bad = ageing_c["good"], ageing_c["bad"]
        xs = [round(0.05 * k, 2) for k in range(10, 31)]

        def index_at(k):
            hs = E.steady_hotspot_cf(k, c["ratio_w"], amb, c["cf"], np_)
            fa = float(ageing_factor(hs, np_))
            lx, ly = zip(*E.LOADING_POINTS)
            comps = held + [{"key": "ageing", "weight": ageing_c["weight"], "score": E._score(fa, good, bad, log2=True)},
                            {"key": "loading", "weight": loading_c["weight"], "score": float(np.interp(k, lx, ly))}]
            return _health_from(comps)
        ys = [index_at(k) for k in xs]
        out["graph"] = _graph(
            "Health index against steady-state load (model)", "Load ratio K (pu)", "Health index (0 to 100)", xs,
            [("Steady-state index", ys)], {"x": _r(ko, 3), "y": h["index"], "label": "index now"},
            f"Ambient held at {amb:.1f} °C; cooling, integrity and unbalance scores held at their present values. "
            "Ageing and loading are recomputed at each load with the engine's own scoring rules. The point is the "
            "reported index and can sit off the curve while the unit is still warming.",
            hlines=[{"y": 80, "label": "80 normal"}, {"y": 40, "label": "40 alarm"}])
        b, a = index_at(ko), index_at(ko * 1.1)
        out["sensitivity"] = [_sens("Load K +10 %", "pu", ko, ko * 1.1, b, a, "points",
                                    note="Steady-state model index at the present load, not the tile; "
                                         "the tile can differ while the unit is still warming.")]
    else:
        out["graph"], out["sensitivity"] = None, []
        out["missing"] = [n for n, v in (("ambient_temp", amb), ("load K", ko)) if v is None]
    out["quality"] = _quality(tw, c, o, extra=[
        "The weights and the +10 cap margin are engineering judgement, stated here rather than fitted to data."])
    return out


